-- Tickets: one row per email that triage classified as property-management work.
create table ticket (
    id                bigint generated by default as identity primary key,
    email_id          varchar(128)  not null,
    received_at       timestamp(6) with time zone not null,
    processed_at      timestamp(6) with time zone not null,
    sender            varchar(1024) not null,
    subject           varchar(2048) not null,
    category          varchar(32)   not null,
    priority          varchar(16)   not null,
    status            varchar(16)   not null,
    unread            boolean       not null,
    sender_type       varchar(128),
    property_address  varchar(1024),
    unit_number       varchar(128),
    rationale         varchar(4096),
    details           clob,
    raw_body          clob,
    constraint uk_ticket_email_id unique (email_id)
);

create index ix_ticket_received_at on ticket (received_at);

-- Every email the pipeline finished with, ticketed or ignored, so a still-unread Gmail
-- message is never sent to the LLM twice. Failed emails are not recorded and get retried.
create table processed_email (
    email_id      varchar(128) not null primary key,
    outcome       varchar(16)  not null,
    processed_at  timestamp(6) with time zone not null
);
